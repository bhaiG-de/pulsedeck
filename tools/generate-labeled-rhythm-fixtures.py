#!/usr/bin/env python3
"""Original deterministic test audio with sample-indexed beat/downbeat labels."""
import argparse
import numpy as np,json,wave
from pathlib import Path
parser=argparse.ArgumentParser(description=__doc__);parser.add_argument('--output',type=Path,default=Path('/tmp/pd-labeled-odd-fixtures'));args=parser.parse_args()
rng=np.random.default_rng(20261014);rate=22050;root=args.output;root.mkdir(parents=True,exist_ok=True)
for meter,bpm in [(4,123),(5,123),(7,173)]:
 period=60/bpm;beats=.21+np.arange(192)*period;duration=beats[-1]+period;x=np.zeros(int(duration*rate),dtype=np.float64)
 for i,t in enumerate(beats):
  at=int(round(t*rate));length=min(int(.24*rate),len(x)-at);tt=np.arange(length)/rate
  bass=0.3*np.sin(2*np.pi*65*tt)*np.exp(-tt*30)
  note=261.63*2**(([0,2,4,5,7,9,11][i%meter])/12)
  piano=.12*sum(np.sin(2*np.pi*note*h*tt)/h for h in [1,2,3,4])*np.exp(-tt*12)
  accent=1.6 if i%meter==0 else 1
  x[at:at+length]+=(bass+piano)*accent
  for hat_t in [t,t+period/2]:
   hat_at=int(round(hat_t*rate));n=min(int(.045*rate),len(x)-hat_at)
   if n>0:x[hat_at:hat_at+n]+=.06*rng.normal(size=n)*np.exp(-np.arange(n)/(rate*.008))
 x=np.clip(x,-.9,.9)
 audio=root/f'own_{meter}beat_{bpm}bpm.wav'
 with wave.open(str(audio),'wb') as f:f.setparams((1,2,rate,0,'NONE','not compressed'));f.writeframes((x*32767).astype('<i2').tobytes())
 (root/(audio.stem+'.reference.json')).write_text(json.dumps({'reference_kind':'Independent sample-indexed synthetic rhythm ground truth; not human-labeled music','provenance':'Generated by this test from sample-indexed onsets and stated cyclic meter; independent deterministic synthetic ground truth, not human-annotated music','beats':beats.tolist(),'downbeats':beats[::meter].tolist(),'bpm':bpm,'meter':meter}))
print(root)
